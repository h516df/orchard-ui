#!/usr/bin/env python3
"""Generate all adapters from the reviewed framework-neutral token source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tokens/orchard.json"


def outputs():
    data = json.loads(SOURCE.read_text())
    schemes = {name: {mode: {**data["neutral"][mode], **palette[mode]} for mode in ("light", "dark")}
               for name, palette in data["palettes"].items()}
    flat = {f"{group}_{key}": value for group in ("spacing", "radius", "size", "type", "motion", "glass")
            for key, value in data[group].items()}
    kotlin = "// Generated by tools/generate_tokens.py; edit tokens/orchard.json.\npackage dev.h516.orchard\n\n"
    kotlin += "internal object OrchardTokenData {\n"
    kotlin += "    val schemes: Map<String, Map<String, Map<String, Long>>> = mapOf(\n"
    for name, modes in schemes.items():
        kotlin += f'        "{name}" to mapOf(\n'
        for mode, colors in modes.items():
            kotlin += f'            "{mode}" to mapOf(\n'
            kotlin += "".join(f'                "{key}" to 0xFF{value[1:]}L,\n' for key, value in colors.items())
            kotlin += "            ),\n"
        kotlin += "        ),\n"
    kotlin += "    )\n}\n\nobject OrchardTokens {\n"
    kotlin += "".join(f"    const val {key} = {value}\n" for key, value in flat.items()) + "}\n"
    ts = "// Generated by tools/generate_tokens.py; edit tokens/orchard.json.\n"
    ts += "export const orchardTokens = " + json.dumps({k: v for k, v in data.items() if k not in ("neutral", "palettes")}, indent=2) + " as const;\n"
    ts += "export const orchardSchemes = " + json.dumps(schemes, indent=2) + " as const;\n"
    ts += "export type OrchardPalette = keyof typeof orchardSchemes;\n"
    ts += 'export type OrchardColors = { [K in keyof typeof orchardSchemes.blue.light]: string };\n'
    dart = "// Generated by tools/generate_tokens.py; edit tokens/orchard.json.\n"
    dart += "const orchardSchemes = <String, Map<String, Map<String, int>>>{\n"
    for name, modes in schemes.items():
        dart += f"  '{name}': {{\n"
        for mode, colors in modes.items():
            dart += f"    '{mode}': {{\n"
            dart += "".join(f"      '{key}': 0xFF{value[1:]},\n" for key, value in colors.items()) + "    },\n"
        dart += "  },\n"
    dart += "};\n\nabstract final class OrchardTokens {\n"
    dart += "".join(f"  static const double {key.split('_')[0] + key.split('_')[1][0].upper() + key.split('_')[1][1:]} = {value};\n" for key, value in flat.items()) + "}\n"
    css = "/* Generated by tools/generate_tokens.py; edit tokens/orchard.json. */\n"
    css += ":root {\n" + "".join(f"  --o-{key.replace('_', '-')}: {value}{'ms' if key.startswith('motion_') else ('' if key == 'glass_tint' else 'px')};\n" for key, value in flat.items()) + "}\n"
    for name, modes in schemes.items():
        for mode, colors in modes.items():
            selector = ":root, " if (name, mode) == ("blue", "light") else ""
            css += selector + f'[data-orchard-palette="{name}"][data-orchard-mode="{mode}"] {{\n'
            css += f"  color-scheme: {mode};\n"
            css += "".join(f"  --o-{key}: {value};\n" for key, value in colors.items()) + "}\n"
    return {
        "adapters/compose/orchard/src/main/java/dev/h516/orchard/GeneratedTokens.kt": kotlin,
        "adapters/react-native/src/tokens.ts": ts,
        "adapters/flutter/lib/src/generated_tokens.dart": dart,
        "adapters/web/tokens.css": css,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    if stale:
        raise SystemExit("Stale tokens; run python3 tools/generate_tokens.py: " + ", ".join(stale))
    print("Token adapters are synchronized." if args.check else "Generated 4 token adapters.")


if __name__ == "__main__":
    main()
